//! The netfilter ruleset that feeds the gateway, rendered from its
//! configuration (`robodr-firewall-gw ruleset --config ...`), so the queue
//! number, the ports and the `on_gateway_down` flag can never disagree with
//! what the gateway expects.
//!
//! The rendered POSIX `sh` script is idempotent (re-running it replaces the
//! gateway's own chains and keeps exactly one jump into each) and is meant
//! for a oneshot unit that runs **before** the gateway and is **not**
//! undone when the gateway stops: the rules must stay in place when the
//! gateway is down, or `fail_closed` would mean nothing.
//!
//! What it sets up (bridge `br0` with ports `controller_port` /
//! `robot_port`; `br_netfilter` hands bridged IPv4 to the iptables hooks):
//!
//! 1. `sysctl`: `bridge-nf-call-iptables=1` (and ip6tables / arptables),
//!    `bridge-nf-filter-vlan-tagged=1`, `bridge-nf-filter-pppoe-tagged=1`.
//! 2. **L2 hygiene** (`nft`, `bridge` family, table `robodr_gw_l2`): from
//!    the controller port only IPv4 and ARP are bridged. IPv6, VLAN-tagged,
//!    PPPoE and every other ethertype are dropped, so no motion command can
//!    reach the robot by a path the gateway does not inspect.
//! 3. **Defragmentation** (`raw` table, chain `ROBODR_GW_RAW`): bridged
//!    traffic of both ports is marked untracked (no conntrack state), and a
//!    no-op `conntrack` match makes the kernel enable IPv4 defragmentation
//!    for the namespace, so a fragmented datagram is reassembled **before**
//!    it is queued (and refragmented on output). `CT --notrack` alone does
//!    not enable it.
//! 4. **Queue** (`filter` table, chain `ROBODR_GW`, jumped to from
//!    `FORWARD` for packets entering on the controller port): any IP
//!    fragment that still reaches it is dropped; UDP to the DDS port range
//!    of each configured domain and to every legacy port goes to
//!    `NFQUEUE --queue-num N`, with `--queue-bypass` only for
//!    `on_gateway_down: bypass`.
//!
//! Tested in this repository with iptables-nft (xtables `physdev`, `CT`,
//! `conntrack` and `NFQUEUE` targets over `nf_tables` compat), which works
//! on kernels built without `CONFIG_NFT_QUEUE`. A native-nft ruleset would
//! need `queue` in the `bridge` family (the `ip` family cannot match the
//! bridge port natively); that variant is not shipped because it could not
//! be tested here.

use crate::config::{GatewayConfig, OnGatewayDown};

/// Render the setup script.
pub fn render(cfg: &GatewayConfig, source: &str) -> String {
    let ctrl = &cfg.queue.controller_port;
    let robot = &cfg.queue.robot_port;
    let bypass = if cfg.queue.on_gateway_down == OnGatewayDown::Bypass {
        " --queue-bypass"
    } else {
        ""
    };
    let num = cfg.queue.num;
    let mut s = String::new();
    s.push_str("#!/bin/sh\n");
    s.push_str(&format!(
        "# Generated by `robodr-firewall-gw ruleset` from {source}. Do not edit:\n\
         # regenerate after changing the gateway configuration.\n\
         # on_gateway_down = {} ({})\n",
        match cfg.queue.on_gateway_down {
            OnGatewayDown::FailClosed => "fail_closed",
            OnGatewayDown::Bypass => "bypass",
        },
        match cfg.queue.on_gateway_down {
            OnGatewayDown::FailClosed => "queued datagrams are dropped while the gateway is down",
            OnGatewayDown::Bypass => "queued datagrams pass UNCHECKED while the gateway is down",
        }
    ));
    s.push_str("set -eu\n");
    s.push_str("IPT=${IPTABLES:-iptables}\n");
    s.push_str(&format!("CTRL='{ctrl}'\nROBOT='{robot}'\n"));
    s.push_str("modprobe br_netfilter 2>/dev/null || true\n");
    for (k, v) in [
        ("net.bridge.bridge-nf-call-iptables", 1),
        ("net.bridge.bridge-nf-call-ip6tables", 1),
        ("net.bridge.bridge-nf-call-arptables", 1),
        ("net.bridge.bridge-nf-filter-vlan-tagged", 1),
        ("net.bridge.bridge-nf-filter-pppoe-tagged", 1),
    ] {
        s.push_str(&format!("sysctl -qw {k}={v}\n"));
    }
    s.push_str(
        "\n# 2. L2 hygiene: only IPv4 and ARP are bridged from the controller side.\n\
         nft -f - <<EOF\n\
         table bridge robodr_gw_l2\n\
         delete table bridge robodr_gw_l2\n\
         table bridge robodr_gw_l2 {\n\
         \x20 chain forward {\n\
         \x20   type filter hook forward priority -200; policy accept;\n\
         \x20   iifname \"$CTRL\" ether type != { ip, arp } counter drop\n\
         \x20 }\n\
         }\n\
         EOF\n",
    );
    s.push_str(
        "\n# 3. Untracked bridged traffic; the conntrack match enables IPv4\n\
         #    defragmentation before the queue.\n\
         $IPT -t raw -N ROBODR_GW_RAW 2>/dev/null || true\n\
         $IPT -t raw -F ROBODR_GW_RAW\n\
         $IPT -t raw -A ROBODR_GW_RAW -j CT --notrack\n\
         $IPT -t raw -A ROBODR_GW_RAW -m conntrack --ctstate UNTRACKED -j RETURN\n\
         for P in \"$CTRL\" \"$ROBOT\"; do\n\
         \x20 $IPT -t raw -C PREROUTING -m physdev --physdev-in \"$P\" -j ROBODR_GW_RAW 2>/dev/null ||\n\
         \x20   $IPT -t raw -I PREROUTING 1 -m physdev --physdev-in \"$P\" -j ROBODR_GW_RAW\n\
         done\n",
    );
    s.push_str("\n# 4. Queue what enters from the controller side.\n");
    s.push_str("$IPT -N ROBODR_GW 2>/dev/null || true\n$IPT -F ROBODR_GW\n");
    s.push_str("$IPT -A ROBODR_GW -f -j DROP\n");
    for (lo, hi) in cfg.rtps_port_ranges() {
        s.push_str(&format!(
            "$IPT -A ROBODR_GW -p udp --dport {lo}:{hi} -j NFQUEUE --queue-num {num}{bypass}\n"
        ));
    }
    for p in cfg.legacy_ports() {
        s.push_str(&format!(
            "$IPT -A ROBODR_GW -p udp --dport {p} -j NFQUEUE --queue-num {num}{bypass}\n"
        ));
    }
    s.push_str(
        "$IPT -C FORWARD -m physdev --physdev-in \"$CTRL\" -j ROBODR_GW 2>/dev/null ||\n\
         \x20 $IPT -I FORWARD 1 -m physdev --physdev-in \"$CTRL\" -j ROBODR_GW\n",
    );
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_queue_flags_and_ports() {
        let mut c = GatewayConfig::from_json(
            r#"{"mode":"enforce","profile":"/p","firewall":"/f",
                "queue":{"num":7,"controller_port":"enp2s0","robot_port":"enp3s0"},
                "rtps":{"domain_ids":[0,1]},
                "channels":[{"firewall_channel":"/lowcmd","codec":"unitree_go_lowcmd"},
                            {"firewall_channel":"/high","codec":"go1_high_cmd"}]}"#,
        )
        .unwrap();
        let s = render(&c, "test.json");
        assert!(s.contains("--dport 7400:7649 -j NFQUEUE --queue-num 7\n"));
        assert!(s.contains("--dport 7650:7899 -j NFQUEUE --queue-num 7\n"));
        assert!(s.contains("--dport 8082 -j NFQUEUE --queue-num 7\n"));
        assert!(!s.contains("queue-bypass"));
        assert!(s.contains("CTRL='enp2s0'"));
        c.queue.on_gateway_down = OnGatewayDown::Bypass;
        let s = render(&c, "test.json");
        assert!(s.contains("--queue-num 7 --queue-bypass\n"));
        assert!(s.contains("UNCHECKED"));
    }
}
