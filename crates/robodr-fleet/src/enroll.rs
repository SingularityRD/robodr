//! One-time enrollment (contract §3): verify the SOC-signed token, generate
//! the unit's keys locally, build the request signed by each new key
//! (uplink, finding, blackbox: proof of possession) and MAC'd with the
//! token secret, submit it (or write it to a file for
//! the air-gapped flow), verify the SOC's signed answer.

use serde::{Deserialize, Serialize};

use crate::client::{self, SocError, SocTransport};
use crate::keys::{self, RoleKey, SocKeys};
use crate::state::{Ctx, Enrollment, PendingEnroll, ENROLLMENT_FORMAT, PENDING_FORMAT};
use crate::wire::{self, EnrollAnswer, EnrollRequest, Envelope, Token, WireError};

/// Keys generated by an unfinished enrollment attempt (so a retry after a
/// crash reuses them instead of refusing them as "existing").
const ENROLL_KEYS: &str = "enroll-keys.json";
const TOKENS_USED: &str = "tokens-used.json";
const PENDING: &str = "enroll-pending.json";
const ENROLLMENT: &str = "enrollment.json";

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct GeneratedKeys {
    fingerprints: Vec<String>,
}

/// Options of [`prepare`].
#[derive(Debug, Clone, Default)]
pub struct EnrollOptions {
    /// Register key files that already exist (e.g. the black-box key of an
    /// agentd that ran before enrollment) instead of refusing them.
    pub reuse_existing_keys: bool,
}

/// The outcome of [`prepare`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Prepared {
    pub pending: PendingEnroll,
    /// `true` when an earlier request for the same token was reused.
    pub resumed: bool,
    /// Per role: `generated` or `reused`.
    pub key_origin: Vec<(String, &'static str)>,
}

fn random_hex16() -> Result<String, String> {
    let mut b = [0u8; 16];
    robodr_blackbox::crypto::fill_random(&mut b).map_err(|e| format!("random: {e}"))?;
    Ok(robodr_blackbox::crypto::to_hex(&b))
}

/// Verify `token_text` and the local bindings, generate (or adopt) the role
/// keys and build the enrollment request. Nothing is sent.
pub fn prepare(ctx: &Ctx, token_text: &str, opt: &EnrollOptions) -> Result<Prepared, String> {
    if let Some(e) = ctx.load::<Enrollment>(ENROLLMENT)? {
        return Err(format!(
            "this unit is already enrolled as {:?} in workspace {:?} (request {}); a new \
             enrollment needs the unit decommissioned first (robodr-enroll decommission; docs/DECOMMISSION.md)",
            e.robot_id, e.workspace, e.request_id
        ));
    }
    // A decommissioned state directory (decommission.json: the receipt) is
    // never enrolled again, whatever keys are on disk: re-commissioning
    // starts from an empty fleet state directory.
    if let Some(d) = crate::decommission::current(ctx)? {
        return Err(format!(
            "this unit was decommissioned ({}, phase {:?}); a decommissioned fleet state \
             directory is not enrolled again. Archive {} (the receipt), then re-commission \
             from new keys and an empty fleet state directory (docs/DECOMMISSION.md, \
             \"Re-commissioning\")",
            d.decommission_id,
            d.phase,
            ctx.path(crate::decommission::STATE_FILE).display()
        ));
    }
    let token = Token::parse(token_text).map_err(|e| format!("token: {e}"))?;
    let tp = &token.payload;
    if let Some(p) = ctx.load::<PendingEnroll>(PENDING)? {
        if p.token_id == tp.token_id {
            return Ok(Prepared {
                pending: p,
                resumed: true,
                key_origin: Vec::new(),
            });
        }
        return Err(format!(
            "an enrollment request for token {:?} is pending (finish it with `robodr-enroll \
             accept --answer FILE`, or remove {} after confirming with the SOC)",
            p.token_id,
            ctx.path(PENDING).display()
        ));
    }
    let soc = SocKeys::load(&ctx.cfg.soc_keys)?;
    let soc_pk = soc.get(&tp.soc_key_id).ok_or_else(|| {
        format!(
            "token is signed by {:?}, which is not a configured SOC fleet key",
            tp.soc_key_id
        )
    })?;
    token.verify(soc_pk).map_err(|e| format!("token: {e}"))?;
    token
        .check_time(ctx.now())
        .map_err(|e| format!("token: {e}"))?;
    if let Some(w) = &ctx.cfg.workspace {
        if *w != tp.workspace {
            return Err(format!(
                "token is for workspace {:?}; this unit is configured for workspace {w:?} \
                 (fleet.json workspace)",
                tp.workspace
            ));
        }
    }
    if let Some(r) = &ctx.facts.robot_id {
        if *r != tp.robot_id {
            return Err(format!(
                "token is for robot {:?}; agentd on this unit is robot {r:?}",
                tp.robot_id
            ));
        }
    }
    if let (Some(s), Some(ts)) = (&ctx.facts.site, &tp.site) {
        if s != ts {
            return Err(format!(
                "token is for site {ts:?}; agentd on this unit is at site {s:?}"
            ));
        }
    }
    if ctx.used(TOKENS_USED, &tp.token_id)? {
        return Err(format!(
            "token {:?} was already used on this unit (single use; ask the SOC for a new one)",
            tp.token_id
        ));
    }

    // Keys.
    let mut generated = ctx.load::<GeneratedKeys>(ENROLL_KEYS)?.unwrap_or_default();
    let mut role_keys: Vec<RoleKey> = Vec::new();
    let mut origin = Vec::new();
    for role in wire::ROLES {
        let path = ctx.cfg.role_key_path(role)?;
        if path.exists() || std::fs::symlink_metadata(path).is_ok() {
            let k = keys::load(role, path)?;
            let ours = generated.fingerprints.contains(&k.fingerprint());
            if !ours && !opt.reuse_existing_keys {
                return Err(format!(
                    "{} already exists ({role} key {}); enrollment generates fresh keys. \
                     Register the existing key with --reuse-existing-keys (e.g. the black-box \
                     key of an agentd that already runs), or move it away",
                    path.display(),
                    k.key_id()
                ));
            }
            origin.push((role.to_string(), if ours { "generated" } else { "reused" }));
            role_keys.push(k);
        } else {
            let k = keys::generate(role, path)?;
            generated.fingerprints.push(k.fingerprint());
            ctx.store(ENROLL_KEYS, &generated)?;
            origin.push((role.to_string(), "generated"));
            role_keys.push(k);
        }
    }

    let profile_digest = match &ctx.facts.profile_path {
        Some(p) => crate::fsx::read_optional(p, 8 * 1024 * 1024)
            .map_err(|e| format!("{}: {e}", p.display()))?
            .map(|b| wire::digest(&b)),
        None => None,
    };
    let req = EnrollRequest {
        format: wire::ENROLL_REQUEST_FORMAT.into(),
        request_id: format!("rfe1-{}", random_hex16()?),
        token_id: tp.token_id.clone(),
        workspace: tp.workspace.clone(),
        robot_id: tp.robot_id.clone(),
        site: tp.site.clone(),
        created_at_ms: ctx.now(),
        agentd_version: env!("CARGO_PKG_VERSION").into(),
        profile_digest,
        keys: role_keys.iter().map(RoleKey::entry).collect(),
    };
    req.check().map_err(|e| format!("request: {e}"))?;
    let envelope = build_request_envelope(&req, &role_keys, &token)?;
    let payload = wire::payload_bytes(&req)?;
    let pending = PendingEnroll {
        format: PENDING_FORMAT.into(),
        token_id: req.token_id.clone(),
        request_id: req.request_id.clone(),
        request_digest: wire::digest(&payload),
        workspace: req.workspace.clone(),
        robot_id: req.robot_id.clone(),
        site: req.site.clone(),
        keys: role_keys.iter().map(RoleKey::reference).collect(),
        envelope: envelope.to_text()?,
        created_at_ms: req.created_at_ms,
    };
    ctx.store(PENDING, &pending)?;
    ctx.mark_used(TOKENS_USED, &tp.token_id)?;
    let mut j = ctx.journal(&req.robot_id)?;
    j.note(&serde_json::json!({
        "kind": crate::journal::K_ENROLL_REQUESTED,
        "token_id": req.token_id,
        "request_id": req.request_id,
        "request_digest": pending.request_digest,
        "workspace": req.workspace,
        "robot_id": req.robot_id,
        "site": req.site,
        "keys": pending.keys,
    }))?;
    j.close()?;
    Ok(Prepared {
        pending,
        resumed: false,
        key_origin: origin,
    })
}

/// The request envelope: signed by every role key it registers, in the
/// request's order (uplink, finding, blackbox: proof of possession of each),
/// and MAC'd with the token.
pub fn build_request_envelope(
    req: &EnrollRequest,
    keys: &[RoleKey],
    token: &Token,
) -> Result<Envelope, WireError> {
    let payload = wire::payload_bytes(req)?;
    let signers: Vec<&robodr_blackbox::Ed25519SigningKey> =
        keys.iter().map(|k| &k.signing).collect();
    let mut e = Envelope::sign(wire::T_ENROLL_REQUEST, &payload, &signers);
    e.mac = Some(wire::EnvMac {
        alg: "hmac-sha256".into(),
        token_id: req.token_id.clone(),
        mac: robodr_blackbox::crypto::to_hex(&wire::token_mac(
            &token.nonce(),
            &req.token_id,
            &payload,
        )),
    });
    Ok(e)
}

/// Submit the pending request and accept the answer.
pub fn submit(ctx: &Ctx, t: &mut dyn SocTransport) -> Result<Enrollment, String> {
    let p = ctx
        .load::<PendingEnroll>(PENDING)?
        .ok_or("no pending enrollment request")?;
    let answer = client::exchange(t, "POST", wire::PATH_ENROLL, p.envelope.as_bytes(), None)
        .map_err(|e| match e {
            SocError::Refused { ref code, .. } if code == "token_used" || code == "token_expired" => {
                format!("{e}; the request stays pending: ask the SOC for a new token and remove {} (OPERATIONS 8.6)", ctx.path(PENDING).display())
            }
            other => other.to_string(),
        })?;
    accept(ctx, &answer)
}

/// Verify the SOC's answer to the pending request and finish enrollment.
pub fn accept(ctx: &Ctx, answer: &[u8]) -> Result<Enrollment, String> {
    let p = ctx
        .load::<PendingEnroll>(PENDING)?
        .ok_or("no pending enrollment request on this unit")?;
    let o = Envelope::parse(answer, wire::T_ENROLL_ANSWER).map_err(|e| format!("answer: {e}"))?;
    let soc = SocKeys::load(&ctx.cfg.soc_keys)?;
    let signer = soc.verify(&o).map_err(|e| format!("answer: {e}"))?;
    let a = EnrollAnswer::parse(&o.payload).map_err(|e| format!("answer: {e}"))?;
    let mism = |what: &str| format!("answer does not match the pending request ({what})");
    if a.request_id != p.request_id || a.request_digest != p.request_digest {
        return Err(mism("request id / digest: an answer to another request"));
    }
    if a.token_id != p.token_id {
        return Err(mism("token"));
    }
    if a.workspace != p.workspace {
        return Err(mism("workspace"));
    }
    if a.robot_id != p.robot_id || a.site != p.site {
        return Err(mism("robot / site"));
    }
    if a.keys != p.keys {
        return Err(mism("registered keys"));
    }
    let e = Enrollment {
        format: ENROLLMENT_FORMAT.into(),
        workspace: a.workspace,
        robot_id: a.robot_id,
        site: a.site,
        token_id: a.token_id,
        request_id: a.request_id,
        request_digest: a.request_digest,
        soc_key_id: signer,
        keys: a.keys,
        enrolled_at_ms: a.enrolled_at_ms,
    };
    ctx.store(ENROLLMENT, &e)?;
    ctx.remove(PENDING)?;
    ctx.remove(ENROLL_KEYS)?;
    let mut j = ctx.journal(&e.robot_id)?;
    j.note(&serde_json::json!({
        "kind": crate::journal::K_ENROLLED,
        "request_id": e.request_id,
        "workspace": e.workspace,
        "robot_id": e.robot_id,
        "site": e.site,
        "soc_key_id": e.soc_key_id,
        "keys": e.keys,
        "answer_digest": o.payload_digest(),
    }))?;
    j.seal()?;
    j.close()?;
    Ok(e)
}
